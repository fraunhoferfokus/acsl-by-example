  let a1 := shift a n in
  let x := Mint1 a1 in
  let x1 := Mint a1 in
  (x = x1) -> is_sint32_chunk Mint -> is_sint32_chunk Mint1 ->
  P_Unchanged_1_ Mint Mint1 a 0%Z n -> is_sint32 x1 -> is_sint32 x ->
  P_Unchanged_1_ Mint Mint1 a 0%Z (1%Z + n)%Z.

Axiom Q_Unchanged_Shift :
