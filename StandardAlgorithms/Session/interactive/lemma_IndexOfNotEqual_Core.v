  forall (Mint:addr -> Numbers.BinNums.Z) (a:addr) (n:Numbers.BinNums.Z)
    (v:Numbers.BinNums.Z) (k:Numbers.BinNums.Z),
  let x := L_IndexOfNotEqual Mint a n v ((-1%Z)%Z + k)%Z in
  ((k < 0%Z)%Z -> ((L_IndexOfNotEqual Mint a n v k) = (-1%Z)%Z)) /\
  (~ (k < 0%Z)%Z ->
   ((n <= 0%Z)%Z -> ((L_IndexOfNotEqual Mint a n v k) = 0%Z)) /\
   (~ (n <= 0%Z)%Z ->
    ((k < (L_CountNotEqual_1_ Mint a 0%Z n v))%Z ->
     ((L_IndexOfNotEqual Mint a n v k) =
      ((1%Z + x)%Z + (L_FindNotEqual_1_ Mint a (1%Z + x)%Z n v))%Z)) /\
    (~ (k < (L_CountNotEqual_1_ Mint a 0%Z n v))%Z ->
     ((L_IndexOfNotEqual Mint a n v k) = n)))).

Axiom Q_IndexOfNotEqual_Lower :
  forall (Mint:addr -> Numbers.BinNums.Z) (a:addr) (v:Numbers.BinNums.Z)
    (n:Numbers.BinNums.Z) (k:Numbers.BinNums.Z),
  (0%Z < n)%Z -> (0%Z <= k)%Z ->
  (k < (L_CountNotEqual_1_ Mint a 0%Z n v))%Z -> is_sint32_chunk Mint ->
  is_sint32 v -> (0%Z <= (L_IndexOfNotEqual Mint a n v k))%Z.

Axiom Q_IndexOfNotEqual_Next :
  forall (Mint:addr -> Numbers.BinNums.Z) (a:addr) (v:Numbers.BinNums.Z)
    (n:Numbers.BinNums.Z) (k:Numbers.BinNums.Z),
  let x := L_IndexOfNotEqual Mint a n v ((-1%Z)%Z + k)%Z in
  (0%Z <= k)%Z -> (0%Z <= n)%Z ->
  (k < (L_CountNotEqual_1_ Mint a 0%Z n v))%Z -> is_sint32_chunk Mint ->
  is_sint32 v ->
  (((1%Z + x)%Z + (L_FindNotEqual_1_ Mint a (1%Z + x)%Z n v))%Z =
   (L_IndexOfNotEqual Mint a n v k)).

Axiom Q_IndexOfNotEqual_Right :
  forall (Mint:addr -> Numbers.BinNums.Z) (a:addr) (v:Numbers.BinNums.Z)
    (n:Numbers.BinNums.Z) (k:Numbers.BinNums.Z),
  (0%Z <= n)%Z -> ((L_CountNotEqual_1_ Mint a 0%Z n v) <= k)%Z ->
  is_sint32_chunk Mint -> is_sint32 v ->
  ((L_IndexOfNotEqual Mint a n v k) = n).

Axiom Q_IndexOfNotEqual_Empty :
  forall (Mint:addr -> Numbers.BinNums.Z) (a:addr) (v:Numbers.BinNums.Z)
    (n:Numbers.BinNums.Z) (k:Numbers.BinNums.Z),
  (n <= 0%Z)%Z -> (0%Z <= k)%Z -> is_sint32_chunk Mint -> is_sint32 v ->
  ((L_IndexOfNotEqual Mint a n v k) = 0%Z).

Axiom Q_IndexOfNotEqual_Left :
  forall (Mint:addr -> Numbers.BinNums.Z) (a:addr) (v:Numbers.BinNums.Z)
    (n:Numbers.BinNums.Z) (k:Numbers.BinNums.Z),
  (k < 0%Z)%Z -> is_sint32_chunk Mint -> is_sint32 v ->
  ((L_IndexOfNotEqual Mint a n v k) = (-1%Z)%Z).

Axiom Q_CountNotEqual_AllEqual :
  forall (Mint:addr -> Numbers.BinNums.Z) (a:addr) (v:Numbers.BinNums.Z)
    (m:Numbers.BinNums.Z) (n:Numbers.BinNums.Z),
  (0%Z <= m)%Z -> (m <= n)%Z -> is_sint32_chunk Mint -> is_sint32 v ->
  P_AllEqual_1_ Mint a m n v -> ((L_CountNotEqual_1_ Mint a m n v) = 0%Z).

Axiom Q_CountNotEqual_SomeNotEqual :
  forall (Mint:addr -> Numbers.BinNums.Z) (a:addr) (v:Numbers.BinNums.Z)
    (m:Numbers.BinNums.Z) (n:Numbers.BinNums.Z),
  (0%Z <= m)%Z -> (m < n)%Z -> (0%Z < (L_CountNotEqual_1_ Mint a m n v))%Z ->
  is_sint32_chunk Mint -> is_sint32 v -> P_SomeNotEqual_1_ Mint a m n v.

Axiom Q_CountNotEqual_FindNotEqual :
  forall (Mint:addr -> Numbers.BinNums.Z) (a:addr) (v:Numbers.BinNums.Z)
    (m:Numbers.BinNums.Z) (n:Numbers.BinNums.Z),
  (0%Z <= m)%Z -> (m < n)%Z -> (0%Z < (L_CountNotEqual_1_ Mint a m n v))%Z ->
  is_sint32_chunk Mint -> is_sint32 v ->
  ((m + (L_FindNotEqual_1_ Mint a m n v))%Z < n)%Z.

Axiom Q_CountNotEqual_Zero :
  forall (Mint:addr -> Numbers.BinNums.Z) (a:addr) (v:Numbers.BinNums.Z)
    (m:Numbers.BinNums.Z) (n:Numbers.BinNums.Z),
  (0%Z <= m)%Z -> (m < n)%Z -> is_sint32_chunk Mint -> is_sint32 v ->
  ((L_CountNotEqual_1_ Mint a m (m + (L_FindNotEqual_1_ Mint a m n v))%Z v) =
   0%Z).

Axiom Q_CountNotEqual_Decrement :
  forall (Mint:addr -> Numbers.BinNums.Z) (a:addr) (v:Numbers.BinNums.Z)
    (m:Numbers.BinNums.Z) (n:Numbers.BinNums.Z),
  (0%Z <= m)%Z -> (m < n)%Z -> is_sint32_chunk Mint -> is_sint32 v ->
  (((L_CountNotEqual_1_ Mint a 0%Z m v) +
    (L_CountNotEqual_1_ Mint a (m + (L_FindNotEqual_1_ Mint a m n v))%Z n v))%Z
   = (L_CountNotEqual_1_ Mint a 0%Z n v)).

Axiom Q_Unchanged_Shrink :
  forall (Mint:addr -> Numbers.BinNums.Z) (Mint1:addr -> Numbers.BinNums.Z)
    (a:addr) (m:Numbers.BinNums.Z) (n:Numbers.BinNums.Z)
